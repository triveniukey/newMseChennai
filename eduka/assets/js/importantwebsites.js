        const itemsPerPage = 16;
        const totalPages = Math.ceil(allWebsites.length / itemsPerPage);

        // Render websites for a given page
        function renderWebsites(page = 1) {
            const container = document.getElementById('websites-container');
            container.innerHTML = '';

            const start = (page - 1) * itemsPerPage;
            const end = start + itemsPerPage;
            const pageItems = allWebsites.slice(start, end);

            pageItems.forEach(item => {
                const div = document.createElement('div');
                div.className = 'notice-item';
                div.innerHTML = `
                    <h4><a href="${item.url}" target="_blank">${item.title}</a></h4>
                    <div class="notice-meta">
                        <span><i class="far fa-building-columns"></i> ${item.desc}</span>
                        <span><a href="${item.url}" target="_blank">${item.url.replace(/^https?:\/\//,'www.')}</a></span>
                    </div>
                `;
                container.appendChild(div);
            });

            renderPagination(page);
        }

        // Render pagination numbers
        function renderPagination(currentPage) {
            const pagination = document.getElementById('pagination');
            pagination.innerHTML = `<li class="page-item"><a class="page-link" href="#" id="prev">       
        <i class="far fa-arrow-left"></i></a></li>`;

            for (let i = 1; i <= totalPages; i++) {
                const li = document.createElement('li');
                li.className = 'page-item';
                if (i === currentPage) li.classList.add('active');
                li.innerHTML = `<a class="page-link" href="#" data-page="${i}">${i}</a>`;
                pagination.appendChild(li);
            }

            pagination.innerHTML += `<li class="page-item"><a class="page-link" href="#" id="next"> <i class="far fa-arrow-right"></i></a></li>`;

            // Event listeners
            document.getElementById('prev').addEventListener('click', (e) => {
                e.preventDefault();
                if (currentPage > 1) renderWebsites(currentPage - 1);
            });

            document.getElementById('next').addEventListener('click', (e) => {
                e.preventDefault();
                if (currentPage < totalPages) renderWebsites(currentPage + 1);
            });

            document.querySelectorAll('#pagination a[data-page]').forEach(link => {
                link.addEventListener('click', (e) => {
                    e.preventDefault();
                    renderWebsites(parseInt(link.getAttribute('data-page')));
                });
            });
        }

        // Load page 1 on start
        window.onload = () => renderWebsites(1);
 



